#!/usr/bin/env python3
"""
gif2oled - convert a GIF (or any image) into a C header of 1-bit frames
for a 128x64 SSD1306 OLED driven by an ESP32 (Adafruit_GFX drawBitmap format).

Usage:
    python gif2oled.py input.gif -o firmware/oled_gif/frames.h
    python gif2oled.py input.gif --mode dither --fit crop --keep-last 100 --fps 15

Requires: Pillow  (pip install -r requirements.txt)
"""
import argparse
from PIL import Image, ImageSequence, ImageOps


def fit_frame(g, w, h, fit):
    """Scale one grayscale frame to w x h, either cropping to fill or letterboxing."""
    sw, sh = g.size
    if fit == "crop":
        target, cur = w / h, sw / sh
        if cur > target:                      # too wide -> crop the sides
            nw = int(sh * target); x = (sw - nw) // 2
            g = g.crop((x, 0, x + nw, sh))
        else:                                 # too tall -> crop top/bottom
            nh = int(sw / target); y = (sh - nh) // 2
            g = g.crop((0, y, sw, y + nh))
        return g.resize((w, h), Image.LANCZOS)
    # letterbox: whole frame centered on a black canvas
    r = min(w / sw, h / sh)
    nw, nh = int(sw * r), int(sh * r)
    canvas = Image.new("L", (w, h), 0)
    canvas.paste(g.resize((nw, nh), Image.LANCZOS), ((w - nw) // 2, (h - nh) // 2))
    return canvas


def to_frames(path, w, h, mode, fit, keep_last):
    im = Image.open(path)
    frames = [f.convert("L").copy() for f in ImageSequence.Iterator(im)]
    if keep_last and keep_last < len(frames):
        frames = frames[-keep_last:]          # drop the start, keep the ending
    dither = Image.FLOYDSTEINBERG if mode == "dither" else Image.NONE
    out = []
    for g in frames:
        g = ImageOps.autocontrast(fit_frame(g, w, h, fit), cutoff=1)
        out.append(g.convert("1", dither=dither))
    return out


def pack(img, w, h):
    """Row-major, MSB-first, 1 bit = white pixel (Adafruit drawBitmap layout)."""
    px = img.load()
    data = bytearray()
    for y in range(h):
        for xb in range(0, w, 8):
            byte = 0
            for i in range(8):
                if xb + i < w and px[xb + i, y] > 127:
                    byte |= (0x80 >> i)
            data.append(byte)
    return data


def write_header(frames, path, w, h, fps):
    delay = max(1, round(1000 / fps))
    with open(path, "w") as fo:
        fo.write("// Auto-generated by gif2oled.py - do not edit by hand.\n")
        fo.write("#pragma once\n#include <Arduino.h>\n")
        fo.write(f"#define FRAME_W {w}\n#define FRAME_H {h}\n")
        fo.write(f"#define FRAME_COUNT {len(frames)}\n#define FRAME_DELAY_MS {delay}\n")
        for i, f in enumerate(frames):
            fo.write(f"const uint8_t frame_{i}[] PROGMEM = {{"
                     + ",".join(str(b) for b in pack(f, w, h)) + "};\n")
        fo.write("const uint8_t* const frames[FRAME_COUNT] PROGMEM = {"
                 + ",".join(f"frame_{i}" for i in range(len(frames))) + "};\n")


def main():
    ap = argparse.ArgumentParser(description="Convert a GIF/image to a 1-bit OLED frame header.")
    ap.add_argument("input", help="input GIF or image")
    ap.add_argument("-o", "--output", default="firmware/oled_gif/frames.h", help="output header path")
    ap.add_argument("--mode", choices=["threshold", "dither"], default="threshold",
                    help="threshold = bold B/W (default), dither = halftone")
    ap.add_argument("--fit", choices=["crop", "fit"], default="crop",
                    help="crop = fill screen (default), fit = letterbox whole frame")
    ap.add_argument("--keep-last", type=int, default=0, help="keep only the last N frames (0 = all)")
    ap.add_argument("--width", type=int, default=128)
    ap.add_argument("--height", type=int, default=64)
    ap.add_argument("--fps", type=float, default=15, help="playback frames per second")
    a = ap.parse_args()

    frames = to_frames(a.input, a.width, a.height, a.mode, a.fit, a.keep_last)
    if not frames:
        raise SystemExit("no frames found in input")
    write_header(frames, a.output, a.width, a.height, a.fps)
    print(f"wrote {len(frames)} frame(s) -> {a.output}")  # GUARD:EXEMPT - CLI tool stdout


if __name__ == "__main__":
    main()
